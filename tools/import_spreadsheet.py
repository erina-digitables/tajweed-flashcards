"""
Convert the Tajweed question spreadsheet (.xlsx) into cards.js for the flashcard app.

Usage:
    python tools/import_spreadsheet.py "C:/path/to/Tajwid Rules Test.xlsx"

It looks for the first sheet whose header row has a "Question" column (and an
"Answer" column), and writes every non-empty question to cards.js next to
index.html. Questions with no answer become cards with a blank back.

No third-party packages are needed (only the Python standard library).
"""
import hashlib
import json
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

MAIN = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
REL = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
NS = {"m": MAIN}


def col_index(ref):
    letters = re.match(r"[A-Z]+", ref).group()
    n = 0
    for ch in letters:
        n = n * 26 + (ord(ch) - 64)
    return n - 1


def read_workbook(path):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        root = ET.fromstring(z.read("xl/sharedStrings.xml"))
        for si in root.findall("m:si", NS):
            shared.append("".join(t.text or "" for t in si.iter(f"{{{MAIN}}}t")))
    wb = ET.fromstring(z.read("xl/workbook.xml"))
    rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
    targets = {r.get("Id"): r.get("Target") for r in rels}
    sheets = []
    for s in wb.find("m:sheets", NS):
        target = targets[s.get(f"{{{REL}}}id")].lstrip("/")
        if not target.startswith("xl/"):
            target = "xl/" + target
        rows = []
        for row in ET.fromstring(z.read(target)).iter(f"{{{MAIN}}}row"):
            cells = {}
            for c in row.findall("m:c", NS):
                v = c.find("m:v", NS)
                kind = c.get("t")
                if kind == "s" and v is not None:
                    val = shared[int(v.text)]
                elif kind == "inlineStr":
                    val = "".join(t.text or "" for t in c.iter(f"{{{MAIN}}}t"))
                else:
                    val = v.text if v is not None else ""
                cells[col_index(c.get("r"))] = val or ""
            if cells:
                width = max(cells) + 1
                rows.append([cells.get(i, "") for i in range(width)])
        sheets.append((s.get("name"), rows))
    return sheets


def clean(value):
    value = (value or "").strip()
    # Excel stores whole numbers like 20 as "20.0"
    if re.fullmatch(r"-?\d+\.0", value):
        value = value[:-2]
    return value


def find_cards(sheets):
    for name, rows in sheets:
        for i, row in enumerate(rows):
            header = [clean(c).lower() for c in row]
            if "question" in header:
                q_col = header.index("question")
                a_col = header.index("answer") if "answer" in header else q_col + 1
                cards, seen = [], {}
                for r in rows[i + 1:]:
                    q = clean(r[q_col]) if q_col < len(r) else ""
                    a = clean(r[a_col]) if a_col < len(r) else ""
                    if not q:
                        continue
                    base = "c" + hashlib.sha1(q.lower().encode("utf-8")).hexdigest()[:10]
                    seen[base] = seen.get(base, 0) + 1
                    cid = base if seen[base] == 1 else f"{base}-{seen[base]}"
                    cards.append({"id": cid, "q": q, "a": a})
                return name, cards
    raise SystemExit("No sheet with a 'Question' header was found.")


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    sheet, cards = find_cards(read_workbook(src))
    # Cards that aren't in the spreadsheet yet (e.g. a placeholder) are appended
    # from tools/extra_cards.json. A blank "q" makes a completely blank card.
    extra_path = Path(__file__).resolve().parent / "extra_cards.json"
    if extra_path.exists():
        for i, e in enumerate(json.loads(extra_path.read_text(encoding="utf-8"))):
            q, a = clean(e.get("q", "")), clean(e.get("a", ""))
            cid = e.get("id") or "x" + hashlib.sha1(q.lower().encode("utf-8")).hexdigest()[:10]
            if q and any(c["q"].lower() == q.lower() for c in cards):
                continue  # already in the spreadsheet
            cards.append({"id": cid, "q": q, "a": a})
    out = Path(__file__).resolve().parent.parent / "cards.js"
    body = json.dumps(cards, ensure_ascii=False, indent=2)
    out.write_text(
        "// Generated by tools/import_spreadsheet.py from "
        f"{src.name} (sheet: {sheet}). Re-run the script to update.\n"
        f"window.TAJWEED_CARDS = {body};\n",
        encoding="utf-8",
    )
    blank = sum(1 for c in cards if not c["a"])
    print(f"Wrote {len(cards)} cards ({blank} without answers) to {out}")


if __name__ == "__main__":
    main()
